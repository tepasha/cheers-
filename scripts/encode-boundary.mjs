#!/usr/bin/env node
// Writes src/data/russiaBoundaryEncoded.ts from src/data/russiaBoundary.json: every ring as a polyline (Google's
// encoding of integer deltas, here in millionths of a degree). The source has at most 6 decimal places, so decoding
// (src/logic/polyline.ts) returns exactly the same numbers; the module is about a third of the JSON and, unlike it,
// compiles to one string per ring instead of tens of thousands of array literals.
//   node scripts/encode-boundary.mjs           write the module
//   node scripts/encode-boundary.mjs --check   exit 1 when the module is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const SCALE = 1e6;
const root = fileURLToPath(new URL('..', import.meta.url));
export const SOURCE_PATH = `${root}src/data/russiaBoundary.json`;
export const MODULE_PATH = `${root}src/data/russiaBoundaryEncoded.ts`;

function encodeSigned(value) {
  let n = value < 0 ? ~(value << 1) : value << 1;
  let out = '';
  while (n >= 0x20) {
    out += String.fromCharCode((0x20 | (n & 0x1f)) + 63);
    n >>= 5;
  }
  return out + String.fromCharCode(n + 63);
}

/** One ring of [lng, lat] points; refuses a coordinate the scale cannot carry exactly */
export function encodeRing(ring) {
  let px = 0;
  let py = 0;
  let out = '';
  for (const [x, y] of ring) {
    const ix = Math.round(x * SCALE);
    const iy = Math.round(y * SCALE);
    if (ix / SCALE !== x || iy / SCALE !== y) throw new Error(`Coordinate [${x}, ${y}] has more than 6 decimal places`);
    out += encodeSigned(ix - px) + encodeSigned(iy - py);
    px = ix;
    py = iy;
  }
  return out;
}

const polygonsOf = (geometry) => (geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates);
const encodePolygons = (polygons) => polygons.map((polygon) => polygon.map(encodeRing));

export function buildModule(boundary) {
  const russia = { source: boundary.source, license: boundary.license, polygons: encodePolygons(polygonsOf(boundary.geometry)) };
  const excluded = {
    source: boundary.exclusions.source,
    reason: boundary.exclusions.reason,
    polygons: encodePolygons(boundary.exclusions.geometries.flatMap(polygonsOf)),
  };
  return [
    '// Generated by scripts/encode-boundary.mjs from russiaBoundary.json (see BOUNDARIES.md). Do not edit by hand.',
    '// Polygons are lists of rings (outer first, then holes); each ring is a polyline of [lng, lat] in millionths of a degree.',
    `export const RUSSIA: { source: string; license: string; polygons: string[][] } = ${JSON.stringify(russia)};`,
    `export const EXCLUDED: { source: string; reason: string; polygons: string[][] } = ${JSON.stringify(excluded)};`,
    '',
  ].join('\n');
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const expected = buildModule(JSON.parse(readFileSync(SOURCE_PATH, 'utf8')));
  if (process.argv.includes('--check')) {
    let current = '';
    // git may check the module out with CRLF (core.autocrlf)
    try { current = readFileSync(MODULE_PATH, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing counts as out of date */ }
    if (current !== expected) {
      console.error('src/data/russiaBoundaryEncoded.ts is out of date: run node scripts/encode-boundary.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(MODULE_PATH, expected);
    console.log(`wrote ${MODULE_PATH} (${expected.length} bytes)`);
  }
}
