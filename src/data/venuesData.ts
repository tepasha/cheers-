// Helper to extract coordinates from Google Maps links or direct inputs
export function parseGoogleMapsInput(input: string): { lat: number; lng: number; name?: string } | null {
  const trimmed = input.trim();
  if (!trimmed) return null;

  // 1. Direct coordinates pair: "50.4635, 30.5180" or "50.4635 30.5180"
  const coordsRegex = /^([+-]?\d{1,2}(?:\.\d+)?)[,\s]+([+-]?\d{1,3}(?:\.\d+)?)$/;
  const coordsMatch = trimmed.match(coordsRegex);
  if (coordsMatch) {
    const lat = parseFloat(coordsMatch[1]);
    const lng = parseFloat(coordsMatch[2]);
    if (lat >= -90 && lat <= 90 && lng >= -180 && lng <= 180) {
      return { lat, lng };
    }
  }

  // 2. Google Maps URL containing @lat,lng or query=lat,lng
  // e.g. https://www.google.com/maps/@50.4418,30.5152,17z
  const urlAtRegex = /@([+-]?\d{1,2}(?:\.\d+)?),([+-]?\d{1,3}(?:\.\d+)?)/;
  const urlAtMatch = trimmed.match(urlAtRegex);
  if (urlAtMatch) {
    const lat = parseFloat(urlAtMatch[1]);
    const lng = parseFloat(urlAtMatch[2]);
    return { lat, lng };
  }

  // 3. Google Maps search query param: query=50.4418,30.5152 or q=50.4418,30.5152
  const queryParamRegex = /[?&](?:query|q)=([+-]?\d{1,2}(?:\.\d+)?),([+-]?\d{1,3}(?:\.\d+)?)/;
  const queryMatch = trimmed.match(queryParamRegex);
  if (queryMatch) {
    const lat = parseFloat(queryMatch[1]);
    const lng = parseFloat(queryMatch[2]);
    return { lat, lng };
  }

  return null;
}
